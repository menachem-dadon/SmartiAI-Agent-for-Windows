import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
const require = createRequire(new URL('../desktop/package.json', import.meta.url));
const { build } = require('esbuild');
const result = await build({ entryPoints: [fileURLToPath(new URL('./lmstudio_bridge.mjs', import.meta.url))],
  outfile: fileURLToPath(new URL('../smarti/local_lmstudio_sdk.cjs', import.meta.url)),
  nodePaths: [fileURLToPath(new URL('../desktop/node_modules', import.meta.url))],
  bundle: true, platform: 'node', target: 'node20', format: 'cjs', minify: true, metafile: true,
  legalComments: 'eof', external: ['bufferutil', 'utf-8-validate'],
  banner: { js: '// Generated by scripts/build_local_model_bridge.mjs; official @lmstudio/sdk 2.1.0. See adjacent NOTICES.' } });
// SDK diagnostic template literals contain indentation-only blank lines. Keep
// the vendored artifact whitespace-clean without changing executable tokens.
const bundle = new URL('../smarti/local_lmstudio_sdk.cjs', import.meta.url);
await writeFile(bundle, (await readFile(bundle, 'utf8')).replace(/^[\t ]+$/gm, ''), 'utf8');
const packageRoots = new Set();
for (const input of Object.keys(result.metafile.inputs)) {
  let folder = path.dirname(path.resolve(input));
  while (folder.includes('node_modules')) {
    try { const data = JSON.parse(await readFile(path.join(folder, 'package.json'), 'utf8')); if (data.name) { packageRoots.add(folder); break; } } catch {}
    folder = path.dirname(folder);
  }
}
const notices = [];
for (const folder of [...packageRoots].sort()) {
  const data = JSON.parse(await readFile(path.join(folder, 'package.json'), 'utf8'));
  notices.push(`${data.name} ${data.version}`);
  for (const name of ['LICENSE', 'LICENSE.md', 'LICENSE.txt', 'license', 'license.md']) {
    try { notices.push(await readFile(path.join(folder, name), 'utf8')); break; } catch {}
  }
}
await writeFile(new URL('../smarti/local_lmstudio_sdk.NOTICES.txt', import.meta.url), notices.join('\n\n'), 'utf8');
